const Z = "2147483647";

function overlay() {
  const host = document.createElement("devkit-picker");
  // Inline styles through the CSSOM: a page's CSP does not apply to them.
  host.style.cssText = `all: initial; position: fixed; inset: 0; z-index: ${Z}; pointer-events: none; display: block; contain: strict;`;
  const shadow = host.attachShadow({ mode: "closed" });
  const box = document.createElement("div");
  box.style.cssText =
    "position: fixed; box-sizing: border-box; border: 2px solid #22d3ee; background: rgba(34, 211, 238, 0.14); border-radius: 2px; display: none; pointer-events: none;";
  const label = document.createElement("div");
  label.style.cssText =
    "position: fixed; display: none; max-width: min(460px, calc(100vw - 16px)); padding: 3px 7px; border-radius: 4px; background: #0b1220; color: #e7e9ee; font: 500 12px/1.4 ui-monospace, 'SF Mono', Menlo, Consolas, monospace; white-space: nowrap; overflow: hidden; text-overflow: ellipsis; box-shadow: 0 2px 8px rgba(0,0,0,.3); pointer-events: none;";
  const hint = document.createElement("div");
  hint.style.cssText =
    "position: fixed; left: 50%; bottom: 14px; transform: translateX(-50%); padding: 6px 12px; border-radius: 6px; background: #0b1220; color: #e7e9ee; font: 12px/1.4 system-ui, -apple-system, 'Segoe UI', sans-serif; white-space: nowrap; box-shadow: 0 4px 16px rgba(0,0,0,.35); pointer-events: none;";
  shadow.append(box, label, hint);
  document.documentElement.append(host);
  try {
    // The top layer puts the overlay above modal dialogs and popovers too.
    host.setAttribute("popover", "manual");
    (host as HTMLElement & { showPopover?: () => void }).showPopover?.();
  } catch {
    /* no popover support: z-index only */
  }
  const place = (el: Element | null) => {
    if (!el) {
      box.style.display = "none";
      label.style.display = "none";
      return;
    }
    const r = el.getBoundingClientRect();
    Object.assign(box.style, { display: "block", left: `${r.left}px`, top: `${r.top}px`, width: `${r.width}px`, height: `${r.height}px` });
    label.replaceChildren();
    const comp = readFramework(el, true)?.components[0]?.name;
    if (comp) {
      const c = document.createElement("span");
      c.style.color = "#67e8f9";
      c.textContent = `<${comp}> `;
      label.append(c);
    }
    label.append(crumbLabel(el));
    const size = document.createElement("span");
    size.style.color = "#a9afbc";
    size.textContent = `  ${Math.round(r.width)} × ${Math.round(r.height)}`;
    label.append(size);
    label.style.display = "block";
    const lh = 24;
    const top = r.top - lh - 4 >= 0 ? r.top - lh - 4 : Math.min(r.bottom + 4, innerHeight - lh - 4);
    label.style.top = `${Math.max(4, top)}px`;
    label.style.left = `${Math.max(4, Math.min(r.left, innerWidth - label.offsetWidth - 4))}px`;
    // Keep the hint out of the way of the element.
    const nearBottom = r.bottom > innerHeight - 60 && r.top < innerHeight;
    Object.assign(hint.style, nearBottom ? { top: "14px", bottom: "auto" } : { top: "auto", bottom: "14px" });
  };
  return { host, box, label, hint, place, remove: () => host.remove() };
}

export function startPicker(): Promise<PickResult> {
  const w = win();
  w.__devkitPicker?.stop("replaced");
  return new Promise<PickResult>((resolve) => {
    const ui = overlay();
    ui.hint.textContent = "Click to pick · ↑ parent · ↓ child · Enter to pick · Esc to cancel";
    let current: Element | null = null;
    let nudged = false;
    const down: Element[] = [];
    let raf = 0;
    const redraw = () => {
      cancelAnimationFrame(raf);
      raf = requestAnimationFrame(() => ui.place(current));
    };
    let cursor: CSSStyleSheet | null = null;
    try {
      cursor = new CSSStyleSheet();
      cursor.replaceSync("* { cursor: crosshair !important; }");
      document.adoptedStyleSheets = [...document.adoptedStyleSheets, cursor];
    } catch {
      cursor = null;
    }
    const targetOf = (e: Event): Element | null => {
      const t = e.composedPath()[0];
      if (!(t instanceof Element) || t === ui.host) return null;
      return t;
    };
    const onMove = (e: Event) => {
      const t = targetOf(e);
      if (!t || (t === current && !nudged)) return;
      current = t;
      nudged = false;
      down.length = 0;
      redraw();
    };
    const block = (e: Event) => {
      if (!targetOf(e)) return;
      e.preventDefault();
      e.stopImmediatePropagation();
    };
    const onDown = (e: Event) => {
      const t = targetOf(e);
      if (!t) return;
      e.preventDefault();
      e.stopImmediatePropagation();
      if ((e as PointerEvent).button !== 0) return;
      stop("picked", nudged && current ? current : t);
    };
    const nudge = (dir: "up" | "down") => {
      if (!current) return;
      if (dir === "up") {
        const p = parentOf(current);
        if (p && p.localName !== "html") {
          down.push(current);
          current = p;
        }
      } else {
        current = down.pop() ?? current.firstElementChild ?? current;
      }
      nudged = true;
      redraw();
    };
    const confirm = () => {
      if (current) stop("picked", current);
    };
    const onKey = (e: KeyboardEvent) => {
      const handled = ["Escape", "ArrowUp", "ArrowDown", "Enter", "[", "]"];
      if (!handled.includes(e.key)) return;
      e.preventDefault();
      e.stopImmediatePropagation();
      if (e.key === "Escape") stop("cancelled");
      else if (e.key === "Enter") confirm();
      else nudge(e.key === "ArrowUp" || e.key === "[" ? "up" : "down");
    };
    const opts = { capture: true, passive: false } as const;
    const swallow = ["mousedown", "pointerup", "mouseup", "click", "dblclick", "auxclick", "contextmenu"];
    window.addEventListener("pointermove", onMove, opts);
    window.addEventListener("pointerdown", onDown, opts);
    for (const t of swallow) window.addEventListener(t, block, opts);
    window.addEventListener("keydown", onKey, opts);
    window.addEventListener("scroll", redraw, { capture: true, passive: true });
    window.addEventListener("resize", redraw);
    const stop = (status: PickResult["status"], picked?: Element) => {
      cancelAnimationFrame(raf);
      window.removeEventListener("pointermove", onMove, opts);
      window.removeEventListener("pointerdown", onDown, opts);
      window.removeEventListener("keydown", onKey, opts);
      window.removeEventListener("scroll", redraw, { capture: true });
      window.removeEventListener("resize", redraw);
      // The click that follows the pointerdown must not reach the page either.
      const release = () => {
        for (const t of swallow) window.removeEventListener(t, block, opts);
      };
      if (status === "picked") {
        const done = () => {
          release();
          window.removeEventListener("click", done, true);
        };
        window.addEventListener("click", done, true);
        setTimeout(done, 800);
      } else release();
      if (cursor) document.adoptedStyleSheets = document.adoptedStyleSheets.filter((s) => s !== cursor);
      ui.remove();
      if (w.__devkitPicker === active) w.__devkitPicker = undefined;
      if (picked) {
        w.__devkitPicked = picked;
        w.__devkitPickedSelector = undefined;
      }
      resolve({ status });
    };
    const active: ActivePicker = { stop, nudge, confirm };
    w.__devkitPicker = active;
  });
}

/** Scrolls to the picked element and outlines it for a moment. */
export function flashPicked(): boolean {
  const el = win().__devkitPicked;
  if (!el?.isConnected) return false;
  el.scrollIntoView({ block: "nearest", inline: "nearest", behavior: "instant" as ScrollBehavior });
  const ui = overlay();
  ui.hint.remove();
  ui.place(el);
  setTimeout(ui.remove, 1200);
  return true;
}

export function installElementPicker(): boolean {
  const w = win();
  if (w.__devkitElement?.v === PICKER_VERSION) return true;
  w.__devkitElement?.cancel();
  w.__devkitElement = {
    v: PICKER_VERSION,
    pick: startPicker,
    cancel: () => win().__devkitPicker?.stop("cancelled"),
    nudge: (dir) => win().__devkitPicker?.nudge(dir),
    confirm: () => win().__devkitPicker?.confirm(),
    picking: () => Boolean(win().__devkitPicker),
    collect: collectPicked,
    flash: flashPicked,
  };
  return true;
}
