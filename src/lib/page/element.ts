/* Selectors */

const TEST_ATTRS = ["data-testid", "data-test-id", "data-test", "data-cy", "data-qa"];

const esc = (s: string) =>
  typeof CSS !== "undefined" && typeof CSS.escape === "function" ? CSS.escape(s) : s.replace(/[^\w-]/g, (c) => `\\${c}`);
const quote = (s: string) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

/** Ids generated by frameworks (React useId, Radix, Headless UI, MUI…) change between renders. */
export function isStableId(id: string): boolean {
  return Boolean(id) && id.length <= 60 && !/^[\d:]|[0-9a-f]{8}-|\d{4,}|^(radix-|headlessui-|react-aria|mui-|ember\d|__|_r_|«)/i.test(id);
}

const UTILITY =
  /^(-?(p|m)[xytrblse]?-|w-|h-|min-|max-|size-|gap|space-|inset|top-|left-|right-|bottom-|z-|text-|font-|leading-|tracking-|bg-|from-|to-|via-|border|rounded|shadow|ring|outline|opacity|flex|grid|col-|row-|items-|justify-|content-|self-|place-|order-|basis-|grow|shrink|block$|inline|hidden$|relative$|absolute$|fixed$|sticky$|static$|overflow|cursor|transition|duration|ease|delay|animate|transform|translate|scale|rotate|skew|origin|select-|pointer-|whitespace|break-|truncate$|underline|uppercase|lowercase|capitalize|italic|sr-only$|container$|aspect-|object-|fill-|stroke-|divide|backdrop|blur|drop-shadow|line-clamp|list-|decoration|align-)/;

/** Classes worth putting in a selector: no Tailwind utilities, no CSS-module or CSS-in-JS hashes. */
export function isStableClass(c: string): boolean {
  return (
    /^[a-zA-Z][\w-]*$/.test(c) &&
    c.length <= 40 &&
    !/\d/.test(c) &&
    !UTILITY.test(c) &&
    !/^(css|sc|jsx|emotion|svelte|astro|ng|_)-?/.test(c)
  );
}

const stableClasses = (el: Element) => Array.from(el.classList).filter(isStableClass);

function isUnique(root: Document | ShadowRoot, selector: string, el: Element): boolean {
  try {
    const all = root.querySelectorAll(selector);
    return all.length === 1 && all[0] === el;
  } catch {
    return false;
  }
}

/** A short CSS selector matching only `el` within its document (or shadow root). */
export function uniqueSelector(el: Element): { selector: string; unique: boolean } {
  const root = el.getRootNode() as Document | ShadowRoot;
  const parts: string[] = [];
  let cur: Element | null = el;
  while (cur && cur.nodeType === 1) {
    if (cur.id && isStableId(cur.id) && isUnique(root, `#${esc(cur.id)}`, cur)) {
      parts.unshift(`#${esc(cur.id)}`);
      break;
    }
    const testAttr = TEST_ATTRS.find((a) => cur!.hasAttribute(a));
    const tag = cur.localName;
    if (testAttr) {
      const sel = `[${testAttr}=${quote(cur.getAttribute(testAttr) ?? "")}]`;
      if (isUnique(root, sel, cur)) {
        parts.unshift(sel);
        break;
      }
    }
    let seg = testAttr ? `${tag}[${testAttr}=${quote(cur.getAttribute(testAttr) ?? "")}]` : tag;
    const name = cur === el ? cur.getAttribute("name") : null;
    if (!testAttr && name && /^(input|select|textarea|button|form|iframe)$/.test(tag)) seg += `[name=${quote(name)}]`;
    else if (!testAttr) {
      const cls = stableClasses(cur)[0];
      if (cls) seg += `.${esc(cls)}`;
    }
    const parent: Element | null = cur.parentElement;
    if (parent && tag !== "html" && tag !== "body") {
      const same = Array.from(parent.children).filter((c) => c.localName === tag);
      let matches = 0;
      try {
        matches = parent.querySelectorAll(`:scope > ${seg}`).length;
      } catch {
        matches = same.length;
      }
      if (matches > 1) seg += `:nth-of-type(${same.indexOf(cur) + 1})`;
    }
    parts.unshift(seg);
    if (isUnique(root, parts.join(" > "), el)) break;
    if (tag === "html") break;
    cur = parent;
  }
  const selector = parts.join(" > ");
  return { selector, unique: isUnique(root, selector, el) };
}

/** The element's parent, crossing out of a shadow root to its host. */
function parentOf(el: Element): Element | null {
  if (el.parentElement) return el.parentElement;
  const root = el.getRootNode();
  return root instanceof ShadowRoot ? root.host : null;
}

export function crumbLabel(el: Element): string {
  const cls = stableClasses(el).slice(0, 2);
  return `${el.localName}${el.id ? `#${el.id}` : ""}${cls.map((c) => `.${c}`).join("")}`;
}

function crumbs(el: Element): Crumb[] {
  const out: Crumb[] = [];
  let cur: Element | null = el;
  let up = 0;
  while (cur && cur.localName !== "html" && up < 60) {
    out.unshift({ label: crumbLabel(cur), up });
    cur = parentOf(cur);
    up++;
  }
  return out;
}

/* HTML */

const VOID = new Set(["area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"]);
const escText = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const escAttr = (s: string) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

/** Indented HTML of `el`, children deeper than `maxDepth` collapsed, long attributes and texts cut. */
export function htmlOf(el: Element, maxDepth: number, maxChildren = 12): { html: string; trimmed: boolean } {
  let trimmed = false;
  const attrs = (e: Element) =>
    Array.from(e.attributes)
      .map((a) => {
        let v = a.value;
        if (/^data:/.test(v)) v = `${v.slice(0, 30)}…`;
        if (v.length > 120) {
          v = `${v.slice(0, 120)}…`;
          trimmed = true;
        }
        return v === "" ? ` ${a.name}` : ` ${a.name}="${escAttr(v)}"`;
      })
      .join("");
  const text = (s: string) => {
    const t = s.replace(/\s+/g, " ").trim();
    if (t.length > 160) trimmed = true;
    return escText(t.length > 160 ? `${t.slice(0, 160)}…` : t);
  };
  const rec = (e: Element, depth: number, pad: string): string => {
    const tag = e.localName;
    const open = `<${tag}${attrs(e)}>`;
    if (VOID.has(tag)) return pad + open;
    const kids = Array.from(e.childNodes).filter((n) => n.nodeType === 1 || (n.nodeType === 3 && n.textContent?.trim()));
    if (!kids.length) return `${pad}${open}</${tag}>`;
    if (tag === "svg" || tag === "script" || tag === "style" || tag === "template") {
      trimmed = true;
      return `${pad}${open}…</${tag}>`;
    }
    if (kids.length === 1 && kids[0]!.nodeType === 3) return `${pad}${open}${text(kids[0]!.textContent ?? "")}</${tag}>`;
    if (depth >= maxDepth) {
      trimmed = true;
      return `${pad}${open}<!-- ${kids.length} child node${kids.length > 1 ? "s" : ""} --></${tag}>`;
    }
    const lines = kids
      .slice(0, maxChildren)
      .map((n) => (n.nodeType === 3 ? `${pad}  ${text(n.textContent ?? "")}` : rec(n as Element, depth + 1, `${pad}  `)));
    if (kids.length > maxChildren) {
      trimmed = true;
      lines.push(`${pad}  <!-- … ${kids.length - maxChildren} more -->`);
    }
    return [pad + open, ...lines, `${pad}</${tag}>`].join("\n");
  };
  return { html: rec(el, 0, ""), trimmed };
}

/** HTML of `el` within `max` characters: collapses deeper levels first, then cuts. */
export function trimmedHtml(el: Element, max = 4096): { html: string; trimmed: boolean } {
  for (let depth = 4; depth >= 0; depth--) {
    const r = htmlOf(el, depth);
    if (r.html.length <= max) return r;
  }
  const r = htmlOf(el, 0, 6);
  return r.html.length <= max ? r : { html: `${r.html.slice(0, max)}\n<!-- … cut -->`, trimmed: true };
}

/* Styles */

function box4(cs: CSSStyleDeclaration, prefix: string, suffix = ""): string | null {
  const v = ["top", "right", "bottom", "left"].map((s) => cs.getPropertyValue(`${prefix}-${s}${suffix}`) || "0px");
  if (v.every((x) => x === "0px")) return null;
  if (v[0] === v[2] && v[1] === v[3]) return v[0] === v[1] ? v[0]! : `${v[0]} ${v[1]}`;
  return v.join(" ");
}

/** The computed styles that usually explain a layout or visual bug, without the defaults. */
export function collectStyles(el: Element): { styles: [string, string][]; parentLayout?: string } {
  const cs = getComputedStyle(el);
  const out: [string, string][] = [];
  const get = (p: string) => cs.getPropertyValue(p).trim();
  const add = (p: string, skip: string[] = []) => {
    const v = get(p);
    if (v && !skip.includes(v)) out.push([p, v]);
  };
  add("display");
  const position = get("position");
  add("position", ["static"]);
  if (position && position !== "static") for (const p of ["top", "right", "bottom", "left"]) add(p, ["auto"]);
  add("z-index", ["auto"]);
  add("box-sizing", ["content-box", "border-box"]);
  add("width", ["auto"]);
  add("height", ["auto"]);
  for (const p of ["min-width", "min-height"]) add(p, ["auto", "0px"]);
  for (const p of ["max-width", "max-height"]) add(p, ["none"]);
  const margin = box4(cs, "margin");
  if (margin) out.push(["margin", margin]);
  const padding = box4(cs, "padding");
  if (padding) out.push(["padding", padding]);
  const widths = ["top", "right", "bottom", "left"].map((s) => get(`border-${s}-width`));
  const styles = ["top", "right", "bottom", "left"].map((s) => get(`border-${s}-style`));
  if (widths.some((w, i) => w && w !== "0px" && styles[i] !== "none")) {
    const same = widths.every((w) => w === widths[0]) && styles.every((s) => s === styles[0]);
    if (same) out.push(["border", `${widths[0]} ${styles[0]} ${get("border-top-color")}`]);
    else
      ["top", "right", "bottom", "left"].forEach((s, i) => {
        if (widths[i] !== "0px" && styles[i] !== "none") out.push([`border-${s}`, `${widths[i]} ${styles[i]} ${get(`border-${s}-color`)}`]);
      });
  }
  add("border-radius", ["0px"]);
  const display = get("display");
  if (/flex/.test(display)) {
    add("flex-direction", ["row"]);
    add("flex-wrap", ["nowrap"]);
    add("justify-content", ["normal", "flex-start"]);
    add("align-items", ["normal", "stretch"]);
    add("gap", ["normal", "0px"]);
  }
  if (/grid/.test(display)) {
    add("grid-template-columns", ["none"]);
    add("grid-template-rows", ["none"]);
    add("gap", ["normal", "0px"]);
    add("justify-items", ["normal", "legacy"]);
    add("align-items", ["normal"]);
  }
  const parent = el.parentElement;
  let parentLayout: string | undefined;
  if (parent) {
    const pcs = getComputedStyle(parent);
    const pd = pcs.getPropertyValue("display");
    if (/flex|grid/.test(pd)) {
      add("flex", ["0 1 auto"]);
      add("align-self", ["auto"]);
      add("order", ["0"]);
      const bits = [`display: ${pd}`];
      for (const p of /flex/.test(pd)
        ? ["flex-direction", "flex-wrap", "justify-content", "align-items", "gap"]
        : ["grid-template-columns", "grid-template-rows", "gap", "align-items"]) {
        const v = pcs.getPropertyValue(p).trim();
        if (v && !["normal", "none", "nowrap", "row", "0px"].includes(v)) bits.push(`${p}: ${v}`);
      }
      parentLayout = `\`${crumbLabel(parent)}\` ${bits.join("; ")}`;
    }
  }
  const family = get("font-family").split(",").slice(0, 2).join(",").trim();
  if (family) out.push(["font-family", family]);
  add("font-size");
  add("font-weight", ["400"]);
  add("line-height", ["normal"]);
  add("letter-spacing", ["normal"]);
  add("text-align", ["start", "left"]);
  add("white-space", ["normal"]);
  add("text-overflow", ["clip"]);
  add("color");
  add("background-color", ["rgba(0, 0, 0, 0)", "transparent"]);
  add("background-image", ["none"]);
  add("box-shadow", ["none"]);
  add("opacity", ["1"]);
  add("visibility", ["visible"]);
  add("overflow", ["visible", "visible visible"]);
  add("transform", ["none"]);
  add("pointer-events", ["auto"]);
  add("cursor", ["auto"]);
  return { styles: out, parentLayout };
}

/* Accessibility, for the Playwright locator */

const NAME_FROM_CONTENT = new Set([
  "button",
  "link",
  "heading",
  "tab",
  "menuitem",
  "option",
  "checkbox",
  "radio",
  "cell",
  "columnheader",
  "switch",
  "treeitem",
]);

export function implicitRole(el: Element): string | undefined {
  const explicit = el.getAttribute("role")?.split(/\s+/)[0];
  if (explicit) return explicit;
  const tag = el.localName;
  const type = (el.getAttribute("type") ?? "text").toLowerCase();
  if (tag === "a" || tag === "area") return el.hasAttribute("href") ? "link" : undefined;
  if (tag === "button") return "button";
  if (tag === "input") {
    if (["button", "submit", "reset", "image"].includes(type)) return "button";
    if (type === "checkbox") return "checkbox";
    if (type === "radio") return "radio";
    if (type === "range") return "slider";
    if (type === "number") return "spinbutton";
    if (type === "search") return "searchbox";
    if (["text", "email", "tel", "url", ""].includes(type)) return "textbox";
    return undefined;
  }
  if (tag === "textarea") return "textbox";
  if (tag === "select") return el.hasAttribute("multiple") || Number(el.getAttribute("size")) > 1 ? "listbox" : "combobox";
  if (/^h[1-6]$/.test(tag)) return "heading";
  if (tag === "img") return el.getAttribute("alt") === "" ? "presentation" : "img";
  const map: Record<string, string> = {
    nav: "navigation",
    main: "main",
    aside: "complementary",
    ul: "list",
    ol: "list",
    li: "listitem",
    table: "table",
    tr: "row",
    td: "cell",
    th: "columnheader",
    dialog: "dialog",
    option: "option",
    progress: "progressbar",
    article: "article",
    form: "form",
    summary: "button",
  };
  return map[tag];
}

const clean = (s: string | null | undefined) => (s ?? "").replace(/\s+/g, " ").trim();

function textOf(el: Element): string {
  // biome-ignore lint/performance/useDomNodeTextContent: innerText skips hidden text and keeps what the user sees
  const t = (el as HTMLElement).innerText;
  return clean(typeof t === "string" && t ? t : el.textContent);
}

export function accessibleName(el: Element, role: string | undefined): { name?: string; label?: string } {
  const label = (el as HTMLInputElement).labels?.[0] ? textOf((el as HTMLInputElement).labels![0]!) : undefined;
  const aria = clean(el.getAttribute("aria-label"));
  if (aria) return { name: aria, label };
  const by = el.getAttribute("aria-labelledby");
  if (by) {
    const t = clean(
      by
        .split(/\s+/)
        .map((id) => (el.ownerDocument.getElementById(id) ? textOf(el.ownerDocument.getElementById(id)!) : ""))
        .join(" "),
    );
    if (t) return { name: t, label };
  }
  if (label) return { name: label, label };
  if (el.localName === "img") return { name: clean(el.getAttribute("alt")) || undefined };
  if (el.localName === "input" && /^(button|submit|reset)$/i.test(el.getAttribute("type") ?? ""))
    return { name: clean((el as HTMLInputElement).value) || undefined };
  if (role && NAME_FROM_CONTENT.has(role)) {
    const t = textOf(el);
    if (t) return { name: t };
  }
  const title = clean(el.getAttribute("title"));
  return { name: title || undefined };
}

/* Frameworks */

type Fiber = {
  tag: number;
  type: unknown;
  elementType?: unknown;
  return: Fiber | null;
  memoizedProps?: unknown;
  _debugSource?: { fileName: string; lineNumber?: number; columnNumber?: number };
  _debugStack?: { stack?: string } | string;
  _debugOwner?: unknown;
};

const COMPONENT_TAGS = new Set([0, 1, 2, 11, 14, 15, 16, 17, 28]);
const KIND: Record<number, string> = { 1: "class", 11: "forwardRef", 14: "memo", 15: "memo", 16: "lazy" };
// Framework components with no source in the app: Next.js App Router, React Router, error overlays.
const INTERNAL =
  /^(InnerLayoutRouter|OuterLayoutRouter|RedirectBoundary|RedirectErrorBoundary|NotFoundBoundary|NotFoundErrorBoundary|LoadingBoundary|ErrorBoundaryHandler|InnerScrollAndFocusHandler|ScrollAndFocusHandler|RenderFromTemplateContext|AppRouter|HotReload|ReactDevOverlay|ServerRoot|HTTPAccessFallbackBoundary|HTTPAccessFallbackErrorBoundary|DevRootHTTPAccessFallbackBoundary|AppDevOverlay|AppDevOverlayErrorBoundary|ClientPageRoot|ClientSegmentRoot|HistoryUpdater|RuntimeStyles|MetadataBoundary|ViewportBoundary|OutletBoundary|PathnameContextProviderAdapter|RenderedRoute|DataRoutes|RouterProvider|Routes|BrowserRouter|Router)$/;

function fiberOf(el: Element): { fiber: Fiber; node: Element } | null {
  let cur: Element | null = el;
  for (let i = 0; cur && i < 30; i++) {
    const key = Object.keys(cur).find((k) => k.startsWith("__reactFiber$") || k.startsWith("__reactInternalInstance$"));
    if (key) return { fiber: (cur as unknown as Record<string, Fiber>)[key]!, node: cur };
    cur = parentOf(cur);
  }
  return null;
}

function fiberSource(f: Fiber): SourceLoc | undefined {
  const s = f._debugSource;
  if (s?.fileName) return { file: s.fileName, line: s.lineNumber, column: s.columnNumber, via: "_debugSource" };
  const stack = typeof f._debugStack === "string" ? f._debugStack : f._debugStack?.stack;
  return stack ? firstUserFrame(stack) : undefined;
}

function readReact(el: Element, light: boolean): FrameworkInfo | null {
  const found = fiberOf(el);
  if (!found) return null;
  const { fiber } = found;
  const components: (ComponentInfo & { fiber: Fiber })[] = [];
  for (let f: Fiber | null = fiber.return, n = 0; f && n < 200; f = f.return, n++) {
    if (!COMPONENT_TAGS.has(f.tag) || typeof f.type === "string") continue;
    const name = reactTypeName(f.elementType ?? f.type);
    const prev = components[components.length - 1];
    if (prev && prev.name === name && (f.tag === 14 || f.tag === 11)) {
      prev.kind = KIND[f.tag];
      continue;
    }
    if (light) return { name: "React", dev: false, components: [{ name }] };
    const source = fiberSource(f);
    components.push({
      name,
      kind: KIND[f.tag],
      source,
      library: (source ? isLibraryUrl(source.file) : false) || INTERNAL.test(name),
      fiber: f,
    });
  }
  if (light) return { name: "React", dev: false, components: [] };
  const dev = "_debugOwner" in fiber || "_debugSource" in fiber || "_debugStack" in fiber;
  const nearest = components.find((c) => !c.library) ?? components[0];
  let version: string | undefined;
  try {
    version = win().__REACT_DEVTOOLS_GLOBAL_HOOK__?.renderers?.values().next().value?.version;
  } catch {
    /* no devtools hook */
  }
  return {
    name: "React",
    version,
    dev,
    components: components.map(({ fiber: _f, ...c }) => c),
    props: nearest ? serializeValue(nearest.fiber.memoizedProps) : undefined,
    propsOf: nearest?.name,
    source: found.node === el ? fiberSource(fiber) : undefined,
  };
}

const baseName = (file: string | undefined) =>
  file
    ?.split(/[\\/]/)
    .pop()
    ?.replace(/\.\w+$/, "");

function readVue3(el: Element, light: boolean): FrameworkInfo | null {
  type Inst = {
    type: { name?: string; __name?: string; __file?: string };
    parent: Inst | null;
    props?: unknown;
    appContext?: { app?: { version?: string } };
  };
  let cur: Element | null = el;
  let inst: Inst | undefined;
  for (let i = 0; cur && i < 30 && !inst; i++, cur = parentOf(cur))
    inst = (cur as unknown as { __vueParentComponent?: Inst }).__vueParentComponent;
  if (!inst) return null;
  const nameOf = (i: Inst) => i.type?.name || i.type?.__name || baseName(i.type?.__file) || "Anonymous";
  if (light) return { name: "Vue 3", dev: false, components: [{ name: nameOf(inst) }] };
  const components: ComponentInfo[] = [];
  for (let i: Inst | null = inst, n = 0; i && n < 60; i = i.parent, n++) {
    const file = i.type?.__file;
    components.push({ name: nameOf(i), source: file ? { file, via: "__file" } : undefined, library: file ? isLibraryUrl(file) : false });
  }
  return {
    name: "Vue 3",
    version: inst.appContext?.app?.version,
    dev: components.some((c) => c.source),
    components,
    props: serializeValue(inst.props),
    propsOf: components[0]?.name,
    source: components[0]?.source,
  };
}

function readVue2(el: Element, light: boolean): FrameworkInfo | null {
  type Vm = {
    $options: { name?: string; _componentTag?: string; __file?: string };
    $parent?: Vm;
    $props?: unknown;
    constructor: { version?: string; super?: { version?: string } };
  };
  let cur: Element | null = el;
  let vm: Vm | undefined;
  for (let i = 0; cur && i < 30 && !vm; i++, cur = parentOf(cur)) vm = (cur as unknown as { __vue__?: Vm }).__vue__;
  if (!vm) return null;
  const nameOf = (v: Vm) => v.$options?.name || v.$options?._componentTag || baseName(v.$options?.__file) || "Anonymous";
  if (light) return { name: "Vue 2", dev: false, components: [{ name: nameOf(vm) }] };
  const components: ComponentInfo[] = [];
  for (let v: Vm | undefined = vm, n = 0; v && n < 60; v = v.$parent, n++) {
    const file = v.$options?.__file;
    components.push({ name: nameOf(v), source: file ? { file, via: "__file" } : undefined, library: file ? isLibraryUrl(file) : false });
  }
  return {
    name: "Vue 2",
    version: vm.constructor?.super?.version ?? vm.constructor?.version,
    dev: components.some((c) => c.source),
    components,
    props: serializeValue(vm.$props),
    propsOf: components[0]?.name,
    source: components[0]?.source,
  };
}

function readSvelte(el: Element, light: boolean): FrameworkInfo | null {
  type Meta = { loc?: { file: string; line: number; column: number; char?: number }; parent?: Parent };
  type Parent = { type?: string; file?: string; line?: number; column?: number; componentTag?: string; parent?: Parent };
  let cur: Element | null = el;
  let meta: Meta | undefined;
  for (let i = 0; cur && i < 30 && !meta; i++, cur = parentOf(cur)) meta = (cur as unknown as { __svelte_meta?: Meta }).__svelte_meta;
  if (!meta?.loc) return null;
  // Svelte 4 counts lines and columns from 0 (and adds `char`); Svelte 5 lines from 1.
  const v4 = meta.loc.char !== undefined;
  const source: SourceLoc = { file: meta.loc.file, line: meta.loc.line + (v4 ? 1 : 0), column: meta.loc.column + 1, via: "__svelte_meta" };
  const components: ComponentInfo[] = [
    { name: baseName(meta.loc.file) ?? "Component", source: { file: meta.loc.file, via: "__svelte_meta" } },
  ];
  for (let p = meta.parent, n = 0; p && n < 60; p = p.parent, n++)
    if (p.type === "component" && p.file)
      components.push({
        name: p.componentTag || baseName(p.file) || "Component",
        source: { file: p.file, line: p.line, column: p.column !== undefined ? p.column + 1 : undefined, via: "__svelte_meta" },
      });
  if (light) return { name: "Svelte", dev: false, components: components.slice(0, 1) };
  return { name: "Svelte", version: v4 ? "4" : "5", dev: true, components, source };
}

function readAngular(el: Element, light: boolean): FrameworkInfo | null {
  const ng = win().ng;
  const version = el.ownerDocument.querySelector("[ng-version]")?.getAttribute("ng-version") ?? undefined;
  if (!ng?.getOwningComponent) return version && !light ? { name: "Angular", version, dev: false, components: [] } : null;
  const nameOf = (c: unknown) => ((c as { constructor?: { name?: string } })?.constructor?.name ?? "Component").replace(/^_+/, "");
  let cmp: unknown;
  try {
    cmp = ng.getComponent?.(el) ?? ng.getOwningComponent(el);
  } catch {
    return null;
  }
  if (!cmp) return null;
  if (light) return { name: "Angular", dev: true, components: [{ name: nameOf(cmp) }] };
  const components: ComponentInfo[] = [];
  const first = cmp;
  for (let n = 0; cmp && n < 40; n++) {
    components.push({ name: nameOf(cmp) });
    const host: Element | null | undefined = ng.getHostElement?.(cmp);
    const above: Element | null = host ? parentOf(host) : null;
    let next: unknown = null;
    try {
      next = above ? ng.getOwningComponent(above) : null;
    } catch {
      next = null;
    }
    cmp = next === cmp ? null : next;
  }
  let props: unknown;
  try {
    const inputs = ng.getDirectiveMetadata?.(first)?.inputs;
    const keys = Array.isArray(inputs) ? inputs : inputs ? Object.keys(inputs) : [];
    if (keys.length) props = serializeValue(Object.fromEntries(keys.map((k) => [k, (first as Record<string, unknown>)[k]])));
  } catch {
    props = undefined;
  }
  return { name: "Angular", version, dev: true, components, props, propsOf: components[0]?.name };
}

export function readFramework(el: Element, light = false): FrameworkInfo | null {
  for (const read of [readReact, readVue3, readVue2, readSvelte, readAngular]) {
    try {
      const r = read(el, light);
      if (r) return r;
    } catch {
      /* a framework's internals changed shape: try the next one */
    }
  }
  return null;
}

