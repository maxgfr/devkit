const KEEP_ATTRS = new Set([
  "role",
  "href",
  "src",
  "alt",
  "title",
  "type",
  "name",
  "placeholder",
  "for",
  "disabled",
  "checked",
  "readonly",
  "required",
  "tabindex",
  "target",
  "rel",
  "action",
  "method",
  "style",
  "hidden",
  "open",
  "lang",
  "dir",
  "contenteditable",
  "draggable",
]);
const LOCATOR_ATTR = /^data-(inspector-|locatorjs|locator$|source|v-inspector|astro-source|qwik-inspector|component-path)/;

export function collectElement(el: Element): ElementInfo {
  const doc = el.ownerDocument;
  const view = doc.defaultView ?? window;
  const attributes: [string, string][] = [];
  for (const a of Array.from(el.attributes)) {
    if (a.name === "class" || a.name === "id" || /^on/.test(a.name) || LOCATOR_ATTR.test(a.name)) continue;
    if (!(KEEP_ATTRS.has(a.name) || a.name.startsWith("aria-") || a.name.startsWith("data-"))) continue;
    if (attributes.length >= 25) break;
    attributes.push([a.name, a.value.length > 200 ? `${a.value.slice(0, 200)}…` : a.value]);
  }
  let locatorAttrs: [string, string][] = [];
  for (let cur: Element | null = el, i = 0; cur && i < 12 && !locatorAttrs.length; cur = parentOf(cur), i++)
    locatorAttrs = Array.from(cur.attributes)
      .filter((a) => LOCATOR_ATTR.test(a.name))
      .map((a) => [a.name, a.value] as [string, string]);
  const r = el.getBoundingClientRect();
  const rect = { x: r.x, y: r.y, width: r.width, height: r.height };
  const vw = view.innerWidth;
  const vh = view.innerHeight;
  const inView = r.width > 0 && r.height > 0 && r.bottom > 0 && r.right > 0 && r.top < vh && r.left < vw;
  const cs = getComputedStyle(el);
  const hidden =
    cs.display === "none"
      ? "display: none"
      : cs.visibility === "hidden"
        ? "visibility: hidden"
        : cs.opacity === "0"
          ? "opacity: 0"
          : r.width === 0 && r.height === 0
            ? "zero size (display: none on an ancestor?)"
            : undefined;
  const { selector, unique } = uniqueSelector(el);
  const root = el.getRootNode();
  const role = implicitRole(el);
  const { name, label } = accessibleName(el, role);
  const testAttr = TEST_ATTRS.find((a) => el.hasAttribute(a));
  const { html, trimmed } = trimmedHtml(el);
  const { styles, parentLayout } = collectStyles(el);
  const framework = readFramework(el) ?? undefined;
  const fromAttrs = sourceFromAttributes(locatorAttrs);
  const fwSource = framework?.source;
  const text = textOf(el);
  return {
    url: view.location.href,
    title: doc.title,
    viewport: { width: vw, height: vh, dpr: view.devicePixelRatio || 1 },
    tag: el.localName,
    id: el.id,
    classes: Array.from(el.classList),
    attributes,
    text: text.length > 300 ? `${text.slice(0, 300)}…` : text,
    html,
    htmlTruncated: trimmed,
    selector,
    selectorUnique: unique,
    shadowHost: root instanceof ShadowRoot ? uniqueSelector(root.host).selector : undefined,
    path: crumbs(el),
    childCount: el.children.length,
    rect,
    inView,
    hidden,
    styles,
    parentLayout,
    role,
    name,
    label,
    placeholder: el.getAttribute("placeholder") ?? undefined,
    testId: testAttr ? { attr: testAttr, value: el.getAttribute(testAttr) ?? "" } : undefined,
    locatorAttrs,
    framework,
    source: fwSource?.line ? fwSource : (fromAttrs ?? fwSource),
  };
}

/** Waits until the page has painted (the overlay gone, the scroll applied). rAF stalls in hidden tabs: cap the wait. */
const painted = () =>
  new Promise<void>((done) => {
    setTimeout(done, 150);
    requestAnimationFrame(() => requestAnimationFrame(() => done()));
  });

export async function collectPicked(options: CollectOptions = {}): Promise<CollectResult> {
  const w = win();
  let el = w.__devkitPicked;
  if (!el) return { status: "none" };
  let refound = false;
  if (!el.isConnected) {
    // Frameworks often replace the node on re-render: find it again by its selector.
    const again = w.__devkitPickedSelector ? document.querySelector(w.__devkitPickedSelector) : null;
    if (!again) return { status: "detached", selector: w.__devkitPickedSelector };
    el = again;
    refound = true;
  }
  for (let i = 0; i < (options.up ?? 0); i++) {
    const p = parentOf(el);
    if (!p || p.localName === "html") break;
    el = p;
  }
  w.__devkitPicked = el;
  if (options.scroll) {
    const r = el.getBoundingClientRect();
    if (r.top < 0 || r.left < 0 || r.bottom > innerHeight || r.right > innerWidth) {
      el.scrollIntoView({ block: r.height > innerHeight ? "start" : "center", inline: "nearest", behavior: "instant" as ScrollBehavior });
    }
    await painted();
  }
  const info = collectElement(el);
  if (info.selectorUnique && !info.shadowHost) w.__devkitPickedSelector = info.selector;
  return { status: "ok", info, refound };
}

