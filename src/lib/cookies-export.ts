// Cookie export formats: Netscape cookies.txt (curl, wget, yt-dlp), JSON and a Cookie header.

/** The fields of `chrome.cookies.Cookie` the formats use. A Chrome cookie fits as is. */
export interface ExportCookie {
  name: string;
  value: string;
  domain: string;
  path: string;
  secure: boolean;
  httpOnly: boolean;
  hostOnly: boolean;
  session: boolean;
  expirationDate?: number;
  sameSite?: string;
  storeId?: string;
  partitionKey?: { topLevelSite?: string; hasCrossSiteAncestor?: boolean };
}

export type ExportFormat = "netscape" | "json" | "header";

export const EXPORT_FORMATS: Record<ExportFormat, { label: string; mime: string; extension: string }> = {
  netscape: { label: "Netscape (cookies.txt)", mime: "text/plain", extension: ".txt" },
  json: { label: "JSON", mime: "application/json", extension: ".json" },
  header: { label: "Header string", mime: "text/plain", extension: ".txt" },
};

export function isExportFormat(v: unknown): v is ExportFormat {
  return typeof v === "string" && v in EXPORT_FORMATS;
}

/** Prefix curl and yt-dlp use for HttpOnly cookies in a cookies.txt file. */
export const HTTP_ONLY_PREFIX = "#HttpOnly_";

const NETSCAPE_HEADER = ["# Netscape HTTP Cookie File", "# https://curl.se/docs/http-cookies.html", "# This file was generated by devkit"];

/** Identity of a cookie in a jar: domain, path, name and, for partitioned cookies, the top-level site. */
export function cookieKey(c: Pick<ExportCookie, "domain" | "path" | "name" | "partitionKey">): string {
  return `${c.domain}${c.path}${c.name}${c.partitionKey ? `@${c.partitionKey.topLevelSite ?? ""}` : ""}`;
}

/** Keeps the first cookie of each `cookieKey`. */
export function dedupeCookies<T extends ExportCookie>(cookies: T[]): T[] {
  const seen = new Set<string>();
  return cookies.filter((c) => {
    const k = cookieKey(c);
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
}

// Tabs and line breaks would break the line format; Chrome never stores them, imported files might.
const clean = (s: string) => s.replace(/[\t\r\n]/g, "");
const bool = (b: boolean) => (b ? "TRUE" : "FALSE");

export interface NetscapeRow {
  domain: string;
  includeSubdomains: "TRUE" | "FALSE";
  path: string;
  secure: "TRUE" | "FALSE";
  /** Unix seconds, 0 for a session cookie. */
  expiry: number;
  name: string;
  value: string;
  httpOnly: boolean;
  partitioned: boolean;
}

/** The seven cookies.txt fields of each cookie, for a table view. */
export function netscapeRows(cookies: ExportCookie[]): NetscapeRow[] {
  return cookies.map((c) => ({
    domain: clean(c.domain),
    includeSubdomains: bool(!c.hostOnly),
    path: clean(c.path || "/"),
    secure: bool(c.secure),
    expiry: c.session || !c.expirationDate ? 0 : Math.floor(c.expirationDate),
    name: clean(c.name),
    value: clean(c.value),
    httpOnly: c.httpOnly,
    partitioned: Boolean(c.partitionKey),
  }));
}

/**
 * Netscape cookies.txt, as curl, wget and yt-dlp read it: one tab-separated line per cookie
 * (domain, include subdomains, path, secure, expiry, name, value), HttpOnly cookies prefixed
 * with `#HttpOnly_`. Cookies already expired at `now` (Unix seconds) are left out.
 */
export function toNetscape(cookies: ExportCookie[], { now = Date.now() / 1000 }: { now?: number } = {}): string {
  const lines = netscapeRows(cookies)
    .filter((r) => r.expiry === 0 || r.expiry > now)
    .map((r) =>
      [`${r.httpOnly ? HTTP_ONLY_PREFIX : ""}${r.domain}`, r.includeSubdomains, r.path, r.secure, String(r.expiry), r.name, r.value].join(
        "\t",
      ),
    );
  return `${[...NETSCAPE_HEADER, "", ...lines].join("\n")}\n`;
}

/** The cookies as a pretty JSON array of Chrome's cookie fields, the shape the cookie editor imports. */
export function toJson(cookies: ExportCookie[]): string {
  return JSON.stringify(cookies, null, 2);
}

/** `name=value; name2=value2`, ready for a `Cookie:` request header. */
export function toHeaderString(cookies: ExportCookie[]): string {
  return cookies.map((c) => (c.name ? `${c.name}=${c.value}` : c.value)).join("; ");
}

export function formatCookies(cookies: ExportCookie[], format: ExportFormat, opts: { now?: number } = {}): string {
  if (format === "json") return toJson(cookies);
  if (format === "header") return toHeaderString(cookies);
  return toNetscape(cookies, opts);
}

/** `<host>_cookies.txt`, `<host>_cookies.json` or `<host>_cookie-header.txt`. */
export function cookiesFileName(host: string, format: ExportFormat): string {
  const safe = host.replace(/[^\w.-]+/g, "_") || "cookies";
  if (format === "json") return `${safe}_cookies.json`;
  if (format === "header") return `${safe}_cookie-header.txt`;
  return `${safe}_cookies.txt`;
}

/** Reads a Netscape cookies.txt file back into cookies. Comments, blank and malformed lines are skipped. */
export function parseNetscape(text: string): ExportCookie[] {
  const out: ExportCookie[] = [];
  for (const raw of text.split(/\r?\n/)) {
    let line = raw.replace(/\r$/, "");
    let httpOnly = false;
    if (line.startsWith(HTTP_ONLY_PREFIX)) {
      httpOnly = true;
      line = line.slice(HTTP_ONLY_PREFIX.length);
    } else if (line.startsWith("#") || !line.trim()) continue;
    const fields = line.split("\t");
    // Some writers drop the trailing tab of an empty value.
    if (fields.length === 6) fields.push("");
    if (fields.length !== 7) continue;
    const [domain, sub, path, secure, expiry, name, value] = fields as [string, string, string, string, string, string, string];
    const expires = Number(expiry);
    if (!domain || !Number.isFinite(expires)) continue;
    const session = expires <= 0;
    out.push({
      name,
      value,
      domain,
      path: path || "/",
      secure: secure.toUpperCase() === "TRUE",
      httpOnly,
      hostOnly: sub.toUpperCase() !== "TRUE",
      session,
      ...(session ? {} : { expirationDate: expires }),
      sameSite: "unspecified",
    });
  }
  return out;
}

/** Cookies from an imported file: a JSON array (devkit's export, or most cookie editors') or a cookies.txt. */
export function parseCookieFile(text: string): ExportCookie[] {
  const trimmed = text.trim();
  if (trimmed.startsWith("[") || trimmed.startsWith("{")) {
    const data = JSON.parse(trimmed) as unknown;
    const items = (Array.isArray(data) ? data : [data]) as Partial<ExportCookie>[];
    return items
      .filter(
        (c): c is Partial<ExportCookie> & { name: string; domain: string } => typeof c?.name === "string" && typeof c.domain === "string",
      )
      .map((c) => ({
        ...c,
        value: c.value ?? "",
        path: c.path ?? "/",
        secure: Boolean(c.secure),
        httpOnly: Boolean(c.httpOnly),
        hostOnly: c.hostOnly ?? !c.domain.startsWith("."),
        session: c.session ?? !c.expirationDate,
      }));
  }
  const cookies = parseNetscape(text);
  if (!cookies.length) throw new Error("no cookie found: expected a JSON array or a Netscape cookies.txt file");
  return cookies;
}
