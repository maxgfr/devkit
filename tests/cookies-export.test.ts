import { describe, expect, it } from "vitest";
import { ACTIONS } from "../src/lib/actions";
import {
  cookieKey,
  cookiesFileName,
  dedupeCookies,
  type ExportCookie,
  formatCookies,
  netscapeRows,
  parseCookieFile,
  parseNetscape,
  toHeaderString,
  toJson,
  toNetscape,
} from "../src/lib/cookies-export";

const NOW = 1_800_000_000;

const cookie = (over: Partial<ExportCookie>): ExportCookie => ({
  name: "sid",
  value: "abc",
  domain: "example.com",
  path: "/",
  secure: false,
  httpOnly: false,
  hostOnly: true,
  session: true,
  sameSite: "lax",
  storeId: "0",
  ...over,
});

const JAR: ExportCookie[] = [
  cookie({ name: "session", value: "abc123" }),
  cookie({
    name: "auth",
    value: "t0k3n",
    domain: ".example.com",
    hostOnly: false,
    secure: true,
    httpOnly: true,
    session: false,
    expirationDate: NOW + 3600.75,
  }),
  cookie({ name: "theme", value: "dark", path: "/app", session: false, expirationDate: NOW + 60 }),
];

const body = (text: string) => text.split("\n").filter((l) => l && !l.startsWith("# ") && l !== "# Netscape HTTP Cookie File");

describe("toNetscape", () => {
  const text = toNetscape(JAR, { now: NOW });

  it("starts with the Netscape header and ends with one newline, without CR", () => {
    expect(text.startsWith("# Netscape HTTP Cookie File\n")).toBe(true);
    expect(text).toContain("# https://curl.se/docs/http-cookies.html");
    expect(text).toContain("# This file was generated by devkit");
    expect(text.endsWith("\n")).toBe(true);
    expect(text.endsWith("\n\n")).toBe(false);
    expect(text).not.toContain("\r");
  });

  it("writes seven tab-separated fields per cookie", () => {
    const lines = body(text);
    expect(lines).toHaveLength(3);
    for (const l of lines) expect(l.split("\t")).toHaveLength(7);
    expect(lines[0]).toBe("example.com\tFALSE\t/\tFALSE\t0\tsession\tabc123");
  });

  it("uses TRUE/FALSE flags, floors the expiry and gives session cookies 0", () => {
    const [, auth, theme] = body(text);
    expect(auth).toBe(`#HttpOnly_.example.com\tTRUE\t/\tTRUE\t${NOW + 3600}\tauth\tt0k3n`);
    expect(theme).toBe(`example.com\tFALSE\t/app\tFALSE\t${NOW + 60}\ttheme\tdark`);
  });

  it("prefixes HttpOnly cookies with #HttpOnly_ (curl, yt-dlp)", () => {
    expect(body(text).filter((l) => l.startsWith("#HttpOnly_"))).toHaveLength(1);
  });

  it("leaves out cookies already expired", () => {
    const out = toNetscape([cookie({ name: "old", session: false, expirationDate: NOW - 1 }), cookie({ name: "now" })], { now: NOW });
    expect(body(out).map((l) => l.split("\t")[5])).toEqual(["now"]);
  });

  it("strips tabs and line breaks that would break the format", () => {
    const out = toNetscape([cookie({ name: "a\tb", value: "x\r\ny" })], { now: NOW });
    expect(body(out)).toEqual(["example.com\tFALSE\t/\tFALSE\t0\tab\txy"]);
  });

  it("is only the header for an empty jar", () => {
    expect(body(toNetscape([], { now: NOW }))).toEqual([]);
  });
});

describe("parseNetscape", () => {
  it("round-trips toNetscape", () => {
    const back = parseNetscape(toNetscape(JAR, { now: NOW }));
    expect(back).toHaveLength(3);
    expect(
      back.map(({ name, value, domain, path, secure, httpOnly, hostOnly, session }) => ({
        name,
        value,
        domain,
        path,
        secure,
        httpOnly,
        hostOnly,
        session,
      })),
    ).toEqual(
      JAR.map(({ name, value, domain, path, secure, httpOnly, hostOnly, session }) => ({
        name,
        value,
        domain,
        path,
        secure,
        httpOnly,
        hostOnly,
        session,
      })),
    );
    expect(back[1]!.expirationDate).toBe(NOW + 3600);
    expect(back[0]!.expirationDate).toBeUndefined();
  });

  it("reads CRLF files, skips comments and malformed lines, and accepts an empty value without its tab", () => {
    const text =
      "# Netscape HTTP Cookie File\r\n\r\n# a comment\r\nbroken line\r\nexample.com\tFALSE\t/\tFALSE\t0\tempty\r\n.x.org\tTRUE\t/\tTRUE\t1900000000\tk\tv\r\n";
    const out = parseNetscape(text);
    expect(out.map((c) => [c.domain, c.name, c.value, c.hostOnly, c.secure, c.session])).toEqual([
      ["example.com", "empty", "", true, false, true],
      [".x.org", "k", "v", false, true, false],
    ]);
  });
});

describe("other formats", () => {
  it("writes a Cookie header string", () => {
    expect(toHeaderString(JAR)).toBe("session=abc123; auth=t0k3n; theme=dark");
    expect(toHeaderString([cookie({ name: "", value: "bare" })])).toBe("bare");
    expect(toHeaderString([])).toBe("");
  });

  it("writes JSON the cookie editor imports back", () => {
    const json = toJson(JAR);
    expect(JSON.parse(json)).toEqual(JAR);
    expect(json).toContain('\n  {\n    "name": "session"');
    expect(parseCookieFile(json).map((c) => c.name)).toEqual(["session", "auth", "theme"]);
  });

  it("imports JSON without hostOnly from the leading dot, and a cookies.txt file", () => {
    const [a, b] = parseCookieFile(
      JSON.stringify([
        { name: "a", value: "1", domain: ".x.org" },
        { name: "b", value: "2", domain: "x.org" },
      ]),
    );
    expect([a!.hostOnly, b!.hostOnly]).toEqual([false, true]);
    expect(parseCookieFile(toNetscape(JAR, { now: NOW }))).toHaveLength(3);
    expect(() => parseCookieFile("nothing here")).toThrow(/no cookie found/);
  });

  it("picks the format by name", () => {
    expect(formatCookies(JAR, "header")).toBe(toHeaderString(JAR));
    expect(formatCookies(JAR, "json")).toBe(toJson(JAR));
    expect(formatCookies(JAR, "netscape", { now: NOW })).toBe(toNetscape(JAR, { now: NOW }));
  });

  it("names the files after the host", () => {
    expect(cookiesFileName("example.com", "netscape")).toBe("example.com_cookies.txt");
    expect(cookiesFileName("example.com", "json")).toBe("example.com_cookies.json");
    expect(cookiesFileName("example.com", "header")).toBe("example.com_cookie-header.txt");
    expect(cookiesFileName("127.0.0.1:8080", "netscape")).toBe("127.0.0.1_8080_cookies.txt");
  });
});

describe("table rows and partitioned cookies", () => {
  it("gives the seven fields and the flags of each cookie", () => {
    expect(netscapeRows(JAR)[1]).toEqual({
      domain: ".example.com",
      includeSubdomains: "TRUE",
      path: "/",
      secure: "TRUE",
      expiry: NOW + 3600,
      name: "auth",
      value: "t0k3n",
      httpOnly: true,
      partitioned: false,
    });
  });

  it("keeps a partitioned cookie apart from the unpartitioned one of the same name, and dedupes repeats", () => {
    const part = cookie({ partitionKey: { topLevelSite: "https://top.example" } });
    expect(cookieKey(part)).not.toBe(cookieKey(cookie({})));
    const out = dedupeCookies([cookie({}), part, cookie({}), { ...part }]);
    expect(out).toHaveLength(2);
    expect(netscapeRows(out).map((r) => r.partitioned)).toEqual([false, true]);
  });
});

describe("Copy cookies.txt action", () => {
  it("asks for the cookies permission and site access", () => {
    const a = ACTIONS.find((x) => x.id === "copy-cookies-txt")!;
    expect(a.keywords).toMatch(/cookies\.txt.*netscape.*curl.*yt-dlp.*wget/);
    expect(a.needs?.({} as never)).toEqual({ permissions: ["cookies"] });
    expect(a.scripts).toBe(true);
  });
});
